//! The type declarations of the project's dependencies: every `*.d.ts`
//! (`.d.mts`, `.d.cts`) under a `node_modules` folder, and every
//! `package.json`, which the TypeScript worker reads to resolve a bare
//! import through its `types` field. Every `node_modules` of the project
//! counts, not just the root's: pnpm and non-hoisted installs keep a
//! workspace member's dependencies next to it, where Node resolution from
//! that member's files finds them first.
//!
//! A package linked from several places (pnpm links every dependency of
//! every member into its store; workspaces link members into the root) is
//! loaded once, under its real path, and the links are reported: the
//! editor resolves through them, as Node does, so TypeScript sees one file
//! however many paths lead to it.
//!
//! The editor gives these to the worker as files it may read, not as files
//! of its program (src/lib/intellisense/worker.ts), so only what the
//! project's code imports is ever parsed. The walk is bounded all the same:
//! the set crosses to the webview as one payload and stays in memory there.

use super::budget::{Collector, Limits, Walk};
use super::{Link, LoadedFiles};
use std::collections::{HashSet, VecDeque};
use std::ffi::OsStr;
use std::fs;
use std::path::{Component, Path, PathBuf};
use walkdir::{DirEntry, WalkDir};

const LIMITS: Limits = Limits {
    max_files: 40_000,
    max_file_bytes: 4 * 1024 * 1024,
    max_total_bytes: 128 * 1024 * 1024,
};
/// Dependency trees are a few packages deep; this only stops a runaway.
const MAX_DEPTH: usize = 40;

/// Folders inside `node_modules` that never take part in Node resolution:
/// pnpm's content store (`.pnpm`, holding every package again under paths
/// nothing resolves to: the top-level links are what TypeScript walks up
/// to), its set-aside copies (`.ignored`) and store (`.store`), caches and
/// binaries, and packages' tests, docs and examples.
const SKIP_DIRS: &[&str] = &[
    ".bin",
    ".cache",
    ".pnpm",
    ".ignored",
    ".store",
    "test",
    "tests",
    "__tests__",
    "coverage",
    "docs",
    "examples",
    ".github",
];

pub fn collect(root: &Path) -> LoadedFiles {
    let mut collector = Collector::new(LIMITS);
    let mut links = Vec::new();
    // Each folder once, whether reached as a `node_modules` of the project
    // or as a link's target. The root's folder goes first, so a limit cuts
    // workspace members off before what every file can see.
    let mut walked = HashSet::new();
    let mut queue: VecDeque<PathBuf> = node_modules_dirs(root).into();
    while let Some(dir) = queue.pop_front() {
        if !walked.insert(dir.clone()) {
            continue;
        }
        let outcome = walk_folder(&dir, &mut collector, &mut links, &mut walked, &mut queue);
        if outcome == Walk::Stop {
            break;
        }
    }
    collector.finish_with_links(links)
}

/// Every `node_modules` folder in the project, the root's first. They are
/// gitignored as a rule, so they are looked for next to each folder the
/// project walk visits rather than walked into.
fn node_modules_dirs(root: &Path) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = super::project_walk(root)
        .flatten()
        .filter(|e| e.file_type().is_some_and(|t| t.is_dir()))
        .map(|e| e.path().join("node_modules"))
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();
    dirs
}

/// Loads the typings under `dir`, without following links: a link to a
/// folder is recorded, and its target queued to be walked once under its
/// own path. So a package linked from several places (every workspace
/// member's `node_modules` under pnpm) is loaded once, and the editor
/// resolves each link to it, as Node does.
fn walk_folder(
    dir: &Path,
    collector: &mut Collector,
    links: &mut Vec<Link>,
    walked: &mut HashSet<PathBuf>,
    queue: &mut VecDeque<PathBuf>,
) -> Walk {
    let mut entries = WalkDir::new(dir)
        .follow_links(false)
        .max_depth(MAX_DEPTH)
        .sort_by_file_name()
        .into_iter()
        .filter_entry(wanted);
    while let Some(Ok(entry)) = entries.next() {
        let path = entry.path();
        if entry.file_type().is_symlink() {
            let Some(target) = link_target(path) else {
                continue;
            };
            if target.is_dir() {
                queue.push_back(folder_to_walk_for(&target));
                links.push(Link {
                    path: path.to_string_lossy().into_owned(),
                    target: target.to_string_lossy().into_owned(),
                });
            } else if let Ok(meta) = fs::metadata(path) {
                // A linked file is loaded as if it were the file itself.
                if collector.add(path, meta.len()) == Walk::Stop {
                    return Walk::Stop;
                }
            }
        } else if entry.file_type().is_dir() {
            // A nested node_modules may be one of the project's own
            // (a linked workspace member's): walked as such, not twice.
            if entry.depth() > 0
                && entry.file_name() == "node_modules"
                && !walked.insert(path.to_path_buf())
            {
                entries.skip_current_dir();
            }
        } else {
            let Ok(meta) = entry.metadata() else { continue };
            if collector.add(path, meta.len()) == Walk::Stop {
                return Walk::Stop;
            }
        }
    }
    Walk::Continue
}

/// What to walk for a link's target. A package in a store sits in a
/// `node_modules` folder of its own, next to links to its dependencies
/// (pnpm: `.pnpm/<pkg>@<v>/node_modules/<pkg>`, with the dependencies
/// linked beside it, at the exact versions it was installed with). Node
/// resolution from the package finds those first, so that folder is walked
/// whole, siblings included; a target outside any `node_modules` (a
/// workspace member) is walked as it is.
fn folder_to_walk_for(target: &Path) -> PathBuf {
    target
        .ancestors()
        .find(|dir| dir.file_name().is_some_and(|name| name == "node_modules"))
        .map(Path::to_path_buf)
        .unwrap_or_else(|| target.to_path_buf())
}

/// Where a link leads, through links to links, as the path Node resolves:
/// relative to the link's folder, `..` and `.` folded, but no further than
/// that (`fs::canonicalize` would also resolve links above the project,
/// giving paths the editor doesn't know). None for a broken or cyclic one.
fn link_target(link: &Path) -> Option<PathBuf> {
    let mut current = link.to_path_buf();
    for _ in 0..8 {
        let Ok(raw) = fs::read_link(&current) else {
            return current.exists().then_some(current);
        };
        let joined = if raw.is_absolute() {
            raw
        } else {
            current.parent()?.join(raw)
        };
        current = fold_dots(&joined);
    }
    None
}

fn fold_dots(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                if !out.pop() {
                    out.push(component);
                }
            }
            other => out.push(other),
        }
    }
    out
}

fn wanted(entry: &DirEntry) -> bool {
    // Links are looked at by the walk itself (a link to a folder is a
    // folder to it, whatever its name says).
    entry.file_type().is_symlink() || is_typing_entry(entry.file_name(), entry.file_type().is_dir())
}

/// Whether a folder is worth descending into, or a file worth loading.
fn is_typing_entry(name: &OsStr, is_dir: bool) -> bool {
    let name = name.to_string_lossy();
    if is_dir {
        return !SKIP_DIRS.contains(&name.as_ref());
    }
    name == "package.json"
        || [".d.ts", ".d.mts", ".d.cts"]
            .iter()
            .any(|ext| name.ends_with(ext))
}

#[tauri::command]
pub async fn load_project_typings(root: String) -> Result<LoadedFiles, String> {
    super::load_from(root, collect).await
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::typings::test_support::{relative_paths, temp_project};

    #[test]
    fn keeps_typings_and_package_json_but_skips_pnpm_store_and_test_dirs() {
        for dir in [
            ".pnpm",
            ".ignored",
            ".store",
            "test",
            "node_modules",
            "solid-js",
        ] {
            assert_eq!(
                is_typing_entry(OsStr::new(dir), true),
                ![".pnpm", ".ignored", ".store", "test"].contains(&dir),
                "dir {dir}"
            );
        }
        for file in ["index.d.ts", "index.d.mts", "index.d.cts", "package.json"] {
            assert!(is_typing_entry(OsStr::new(file), false), "file {file}");
        }
        for file in ["index.js", "index.d.ts.map", "README.md", "index.ts"] {
            assert!(!is_typing_entry(OsStr::new(file), false), "file {file}");
        }
    }

    #[test]
    fn loads_declarations_of_every_package_including_nested_ones() {
        let dir = temp_project(
            "typings-walk",
            &[
                ("node_modules/a/package.json", "{}"),
                ("node_modules/a/index.d.ts", "export {}"),
                ("node_modules/a/index.js", "x"),
                ("node_modules/a/node_modules/b/types.d.mts", "export {}"),
                (
                    "node_modules/@types/node/index.d.ts",
                    "declare var process: any",
                ),
                (
                    "node_modules/.pnpm/a@1/node_modules/a/index.d.ts",
                    "export {}",
                ),
                ("node_modules/a/test/a.d.ts", "export {}"),
                ("src/own.d.ts", "export {}"),
            ],
        );
        let loaded = collect(&dir);
        assert!(!loaded.truncated);
        assert_eq!(
            relative_paths(&dir, &loaded),
            [
                "node_modules/@types/node/index.d.ts",
                "node_modules/a/index.d.ts",
                "node_modules/a/node_modules/b/types.d.mts",
                "node_modules/a/package.json",
            ]
        );
    }

    #[test]
    fn workspace_members_have_their_own_dependencies() {
        let dir = temp_project(
            "typings-workspace",
            &[
                (".gitignore", "node_modules\ndist\n"),
                ("node_modules/shared/index.d.ts", "export {}"),
                ("packages/app/package.json", "{}"),
                (
                    "packages/app/node_modules/only-here/index.d.ts",
                    "export {}",
                ),
                ("packages/app/src/a.ts", "x"),
                ("dist/node_modules/built/index.d.ts", "export {}"),
            ],
        );
        let loaded = collect(&dir);
        assert_eq!(
            relative_paths(&dir, &loaded),
            [
                "node_modules/shared/index.d.ts",
                "packages/app/node_modules/only-here/index.d.ts",
            ]
        );
    }

    #[test]
    fn a_project_without_dependencies_loads_nothing() {
        let dir = temp_project("typings-none", &[("src/a.ts", "x")]);
        let loaded = collect(&dir);
        assert!(loaded.files.is_empty() && !loaded.truncated);
    }

    #[cfg(unix)]
    #[test]
    fn linked_packages_load_once_under_their_real_path_with_the_links_reported() {
        use std::os::unix::fs::symlink;
        let dir = temp_project(
            "typings-links",
            &[
                (".gitignore", "node_modules\n"),
                (
                    "node_modules/.pnpm/foo@1/node_modules/foo/package.json",
                    "{}",
                ),
                (
                    "node_modules/.pnpm/foo@1/node_modules/foo/index.d.ts",
                    "export {}",
                ),
                (
                    "node_modules/.pnpm/bar@2/node_modules/bar/index.d.ts",
                    "export {}",
                ),
                (
                    "node_modules/.pnpm/unused@1/node_modules/unused/index.d.ts",
                    "export {}",
                ),
                ("packages/lib/package.json", "{}"),
                ("packages/lib/dist/index.d.ts", "export {}"),
                ("packages/lib/node_modules/own/index.d.ts", "export {}"),
                ("packages/app/package.json", "{}"),
            ],
        );
        // pnpm: the root's and a member's `foo` both link into the store;
        // a workspace member is linked into the root under its name.
        symlink(".pnpm/foo@1/node_modules/foo", dir.join("node_modules/foo")).unwrap();
        // foo's own dependency, linked beside it in the store.
        symlink(
            "../../bar@2/node_modules/bar",
            dir.join("node_modules/.pnpm/foo@1/node_modules/bar"),
        )
        .unwrap();
        fs::create_dir_all(dir.join("packages/app/node_modules")).unwrap();
        symlink(
            "../../../node_modules/.pnpm/foo@1/node_modules/foo",
            dir.join("packages/app/node_modules/foo"),
        )
        .unwrap();
        fs::create_dir_all(dir.join("node_modules/@scope")).unwrap();
        symlink("../../packages/lib", dir.join("node_modules/@scope/lib")).unwrap();
        symlink("missing", dir.join("node_modules/broken")).unwrap();

        let loaded = collect(&dir);
        assert_eq!(
            relative_paths(&dir, &loaded),
            [
                "node_modules/.pnpm/bar@2/node_modules/bar/index.d.ts",
                "node_modules/.pnpm/foo@1/node_modules/foo/index.d.ts",
                "node_modules/.pnpm/foo@1/node_modules/foo/package.json",
                "packages/lib/dist/index.d.ts",
                "packages/lib/node_modules/own/index.d.ts",
                "packages/lib/package.json",
            ]
        );
        let mut links: Vec<(String, String)> = loaded
            .links
            .iter()
            .map(|l| {
                let rel = |p: &str| {
                    Path::new(p)
                        .strip_prefix(&dir)
                        .unwrap()
                        .to_string_lossy()
                        .replace('\\', "/")
                };
                (rel(&l.path), rel(&l.target))
            })
            .collect();
        links.sort();
        assert_eq!(
            links,
            [
                (
                    "node_modules/.pnpm/foo@1/node_modules/bar".into(),
                    "node_modules/.pnpm/bar@2/node_modules/bar".into()
                ),
                ("node_modules/@scope/lib".into(), "packages/lib".into()),
                (
                    "node_modules/foo".into(),
                    "node_modules/.pnpm/foo@1/node_modules/foo".into()
                ),
                (
                    "packages/app/node_modules/foo".into(),
                    "node_modules/.pnpm/foo@1/node_modules/foo".into()
                ),
            ]
        );
    }
}
