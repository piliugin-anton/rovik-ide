//! The type declarations of the project's dependencies: every `*.d.ts`
//! (`.d.mts`, `.d.cts`) under a `node_modules` folder, and every
//! `package.json`, which the TypeScript worker reads to resolve a bare
//! import through its `types` field. Every `node_modules` of the project
//! counts, not just the root's: pnpm and non-hoisted installs keep a
//! workspace member's dependencies next to it, where Node resolution from
//! that member's files finds them first.
//!
//! The editor gives these to the worker as files it may read, not as files
//! of its program (src/lib/intellisense/worker.ts), so only what the
//! project's code imports is ever parsed. The walk is bounded all the same:
//! the set crosses to the webview as one payload and stays in memory there.

use super::budget::{Collector, Limits, Walk};
use super::LoadedFiles;
use std::collections::HashSet;
use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};
use walkdir::{DirEntry, WalkDir};

const LIMITS: Limits = Limits {
    max_files: 40_000,
    max_file_bytes: 4 * 1024 * 1024,
    max_total_bytes: 128 * 1024 * 1024,
};
/// Dependency trees are a few packages deep; this only stops a runaway.
const MAX_DEPTH: usize = 40;

/// Folders inside `node_modules` that never take part in Node resolution:
/// pnpm's content store (`.pnpm`, holding every package again under paths
/// nothing resolves to: the top-level links are what TypeScript walks up
/// to), its set-aside copies (`.ignored`) and store (`.store`), caches and
/// binaries, and packages' tests, docs and examples.
const SKIP_DIRS: &[&str] = &[
    ".bin",
    ".cache",
    ".pnpm",
    ".ignored",
    ".store",
    "test",
    "tests",
    "__tests__",
    "coverage",
    "docs",
    "examples",
    ".github",
];

pub fn collect(root: &Path) -> LoadedFiles {
    let mut collector = Collector::new(LIMITS);
    // Symlinked packages (workspaces, pnpm) are followed, each real target
    // once: a link cycle, or one target linked from several places (a
    // workspace member from the root and from a sibling), is never walked
    // twice. The root's folder goes first, so a limit cuts members off
    // before what every file can see.
    let mut seen = HashSet::new();
    for dir in node_modules_dirs(root) {
        if walk_node_modules(&dir, &mut collector, &mut seen) == Walk::Stop {
            break;
        }
    }
    collector.finish()
}

/// Every `node_modules` folder in the project, the root's first. They are
/// gitignored as a rule, so they are looked for next to each folder the
/// project walk visits rather than walked into.
fn node_modules_dirs(root: &Path) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = super::project_walk(root)
        .flatten()
        .filter(|e| e.file_type().is_some_and(|t| t.is_dir()))
        .map(|e| e.path().join("node_modules"))
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();
    dirs
}

fn walk_node_modules(
    node_modules: &Path,
    collector: &mut Collector,
    seen: &mut HashSet<PathBuf>,
) -> Walk {
    let walker = WalkDir::new(node_modules)
        .follow_links(true)
        .max_depth(MAX_DEPTH)
        .sort_by_file_name()
        .into_iter()
        .filter_entry(|entry| wanted(entry, seen));
    for entry in walker.filter_map(Result::ok) {
        if !entry.file_type().is_file() {
            continue;
        }
        let Ok(meta) = entry.metadata() else { continue };
        if collector.add(entry.path(), meta.len()) == Walk::Stop {
            return Walk::Stop;
        }
    }
    Walk::Continue
}

fn wanted(entry: &DirEntry, seen: &mut HashSet<PathBuf>) -> bool {
    if entry.path_is_symlink() {
        match fs::canonicalize(entry.path()) {
            Ok(target) => {
                if !seen.insert(target) {
                    return false;
                }
            }
            Err(_) => return false, // broken link
        }
    }
    is_typing_entry(entry.file_name(), entry.file_type().is_dir())
}

/// Whether a folder is worth descending into, or a file worth loading.
fn is_typing_entry(name: &OsStr, is_dir: bool) -> bool {
    let name = name.to_string_lossy();
    if is_dir {
        return !SKIP_DIRS.contains(&name.as_ref());
    }
    name == "package.json"
        || [".d.ts", ".d.mts", ".d.cts"]
            .iter()
            .any(|ext| name.ends_with(ext))
}

#[tauri::command]
pub async fn load_project_typings(root: String) -> Result<LoadedFiles, String> {
    super::load_from(root, collect).await
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::typings::test_support::{relative_paths, temp_project};

    #[test]
    fn keeps_typings_and_package_json_but_skips_pnpm_store_and_test_dirs() {
        for dir in [
            ".pnpm",
            ".ignored",
            ".store",
            "test",
            "node_modules",
            "solid-js",
        ] {
            assert_eq!(
                is_typing_entry(OsStr::new(dir), true),
                ![".pnpm", ".ignored", ".store", "test"].contains(&dir),
                "dir {dir}"
            );
        }
        for file in ["index.d.ts", "index.d.mts", "index.d.cts", "package.json"] {
            assert!(is_typing_entry(OsStr::new(file), false), "file {file}");
        }
        for file in ["index.js", "index.d.ts.map", "README.md", "index.ts"] {
            assert!(!is_typing_entry(OsStr::new(file), false), "file {file}");
        }
    }

    #[test]
    fn loads_declarations_of_every_package_including_nested_ones() {
        let dir = temp_project(
            "typings-walk",
            &[
                ("node_modules/a/package.json", "{}"),
                ("node_modules/a/index.d.ts", "export {}"),
                ("node_modules/a/index.js", "x"),
                ("node_modules/a/node_modules/b/types.d.mts", "export {}"),
                (
                    "node_modules/@types/node/index.d.ts",
                    "declare var process: any",
                ),
                (
                    "node_modules/.pnpm/a@1/node_modules/a/index.d.ts",
                    "export {}",
                ),
                ("node_modules/a/test/a.d.ts", "export {}"),
                ("src/own.d.ts", "export {}"),
            ],
        );
        let loaded = collect(&dir);
        assert!(!loaded.truncated);
        assert_eq!(
            relative_paths(&dir, &loaded),
            [
                "node_modules/@types/node/index.d.ts",
                "node_modules/a/index.d.ts",
                "node_modules/a/node_modules/b/types.d.mts",
                "node_modules/a/package.json",
            ]
        );
    }

    #[test]
    fn workspace_members_have_their_own_dependencies() {
        let dir = temp_project(
            "typings-workspace",
            &[
                (".gitignore", "node_modules\ndist\n"),
                ("node_modules/shared/index.d.ts", "export {}"),
                ("packages/app/package.json", "{}"),
                (
                    "packages/app/node_modules/only-here/index.d.ts",
                    "export {}",
                ),
                ("packages/app/src/a.ts", "x"),
                ("dist/node_modules/built/index.d.ts", "export {}"),
            ],
        );
        let loaded = collect(&dir);
        assert_eq!(
            relative_paths(&dir, &loaded),
            [
                "node_modules/shared/index.d.ts",
                "packages/app/node_modules/only-here/index.d.ts",
            ]
        );
    }

    #[test]
    fn a_project_without_dependencies_loads_nothing() {
        let dir = temp_project("typings-none", &[("src/a.ts", "x")]);
        let loaded = collect(&dir);
        assert!(loaded.files.is_empty() && !loaded.truncated);
    }

    #[cfg(unix)]
    #[test]
    fn a_target_linked_twice_is_walked_once() {
        let dir = temp_project(
            "typings-links",
            &[
                ("packages/lib/index.d.ts", "export {}"),
                ("packages/lib/package.json", "{}"),
            ],
        );
        fs::create_dir_all(dir.join("node_modules")).unwrap();
        for link in ["lib", "lib-again"] {
            std::os::unix::fs::symlink(
                dir.join("packages/lib"),
                dir.join("node_modules").join(link),
            )
            .unwrap();
        }
        let loaded = collect(&dir);
        assert_eq!(
            relative_paths(&dir, &loaded),
            [
                "node_modules/lib/index.d.ts",
                "node_modules/lib/package.json"
            ]
        );
    }
}
